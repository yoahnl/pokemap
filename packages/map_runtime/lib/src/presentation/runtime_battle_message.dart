final class RuntimeBattleMessage {
  const RuntimeBattleMessage(
    this.id,
    this.fallbackText, {
    this.actor = '',
    this.target = '',
    this.replacement = '',
    this.move = '',
    this.previousMove = '',
    this.item = '',
    this.amount = 0,
    this.maximum = 0,
    this.stat,
  });

  final RuntimeBattleMessageId id;
  final String fallbackText;
  final String actor;
  final String target;
  final String replacement;
  final String move;
  final String previousMove;
  final String item;
  final int amount;
  final int maximum;
  final BattleStatId? stat;

  String render(RuntimeBattleMessageRenderer? formatter) =>
      formatter?.call(this) ?? fallbackText;
}
