    final raster = rasterizeGen5McssDsRotatedQuad(
      atlas: Gen5IndexedAtlas.fromIndices(Uint8List(256 * 128)),
      width: 8,
      height: 8,
      vertices: const [
        (x: 4, y: 0, u: 0, v: 0, w: 4096),
        (x: 0, y: 4, u: 0, v: 64, w: 4096),
        (x: 4, y: 8, u: 64, v: 64, w: 4096),
        (x: 8, y: 4, u: 64, v: 0, w: 4096),
