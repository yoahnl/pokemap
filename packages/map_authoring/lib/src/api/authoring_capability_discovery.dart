Map<String, Object?> describeAuthoringCapabilities(
  Map<String, Object?> description, {
  String domain = 'all',
  String view = 'full',
  List<String> actionIds = const [],
}) {
  if (domain != 'all' && !authoringCapabilityDomains.containsKey(domain)) {
    throw FormatException('Unsupported capability domain: $domain');
  }
  if (view != 'full' && view != 'compact') {
    throw FormatException('Unsupported capability view: $view');
  }
  if (actionIds.length > 64 ||
      actionIds.toSet().length != actionIds.length ||
      actionIds.any((id) => id.trim().isEmpty)) {
    throw const FormatException(
        'actionIds must contain at most 64 distinct non-empty identities.');
  }
  if (domain == 'all' && view == 'full' && actionIds.isEmpty) {
    return description;
  }
  final available = [
    for (final raw in description['mutationActions'] as List? ?? const [])
      Map<String, Object?>.from(raw as Map),
  ];
  final byId = {for (final action in available) action['id']: action};
  for (final id in actionIds) {
    if (!byId.containsKey(id) || !_inDomain(id, domain)) {
      throw FormatException('Unknown action in capability domain $domain: $id');
    }
  }
  final selected = available
      .where((action) =>
          _inDomain(action['id'] as String, domain) &&
          (actionIds.isEmpty || actionIds.contains(action['id'])))
      .toList()
    ..sort((a, b) => (a['id'] as String).compareTo(b['id'] as String));
  final resources = {
    for (final action in selected)
      for (final kind in action['resourceKinds'] as List? ?? const []) kind,
  };
  final effectiveView = actionIds.isEmpty ? view : 'full';
  return {
    'capabilityDiscoveryVersion': 1,
    'domain': domain,
    'view': effectiveView,
    'classification': 'canonical_action_families_v1',
    if (description['protocol'] != null) 'protocol': description['protocol'],
    if (description['schemaVersion'] != null)
      'schemaVersion': description['schemaVersion'],
    'actionCount': selected.length,
    'mutationActions': [
      for (final action in selected)
        if (effectiveView == 'full') action else _compactAction(action),
    ],
    'resourceKinds': [
      for (final raw in description['resourceKinds'] as List? ?? const [])
        if (resources.contains((raw as Map)['id']))
          if (effectiveView == 'full')
            raw
          else
            {
              'id': raw['id'],
              if (raw['version'] != null) 'version': raw['version'],
              if ((raw['extensions'] as Map?)?['query'] != null)
                'query': (raw['extensions'] as Map)['query'],
            },
    ],
    if (description['queryOperations'] != null)
      'queryOperations': description['queryOperations'],
    'detailRequest': {
      'view': 'full',
      'domain': domain,
      'actionIds': ['<actionId>']
    },
  };
}

bool _inDomain(String id, String domain) =>
    domain == 'all' || authoringCapabilityDomains[domain]!.contains(id);

Map<String, Object?> _compactAction(Map<String, Object?> action) {
  final extensions = action['extensions'] as Map?;
  return {
    for (final key in [
      'id',
      'version',
      'summary',
      'riskLevel',
      'requiredPermissions',
      'guarantees'
    ])
      if (action.containsKey(key)) key: action[key],
    'inputSchemaAvailable': extensions?['inputSchema'] is Map,
    if (extensions != null)
      'constraints': {
        for (final entry in extensions.entries)
          if ((entry.key as String).startsWith('maximum') ||
              const {
                'batchAtomicity',
                'undoBoundary',
                'supportedFieldKinds',
                'visualKinds',
                'rawTilesetRequired',
                'dependentSpatialBorders'
              }.contains(entry.key))
            entry.key as String: entry.value,
      },
  };
}
