Future<void> main(List<String> arguments) async {
  try {
    final options = parseSelbrumePortReferenceAssetOptions(arguments);
    final result = await buildSelbrumePortReferenceAssets(options);
    if (result.divergentRelativePaths.isEmpty) {
      stdout.writeln('Port reference assets are up to date.');
    } else {
      stderr.writeln('Port reference asset divergence:');
      for (final path in result.divergentRelativePaths) {
        stderr.writeln('  $path');
      }
    }
    exitCode = result.exitCode;
  } catch (error, stackTrace) {
    stderr.writeln('Port reference asset build failed: $error');
    stderr.writeln(stackTrace);
    exitCode = 1;
  }
}
